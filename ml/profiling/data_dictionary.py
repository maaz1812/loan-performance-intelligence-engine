KIND_LABEL = {
    IDENTIFIER: "Identifier",
    TIME: "Time",
    ACQUISITION: "Acquisition",
    PERFORMANCE: "Performance",
    CREDIT_EVENT: "Credit event",
    UNUSED: "Unused",
}


def profile_corpus(n_files: int = 4, n_rows: int = 30_000) -> dict:
    """
    Profile a spread of archives to establish observed field behaviour.

    A strided sample is used rather than the file head: the first rows of a
    Fannie Mae file all belong to one loan's earliest months, which badly
    misrepresents fill rates for monthly fields.
    """
    zips = raw_zips()
    if not zips:
        return {}
    picks = [zips[0], zips[len(zips) // 3], zips[2 * len(zips) // 3], zips[-1]][:n_files]

    agg: dict[int, dict] = {
        i: {"fill": [], "distinct": [], "examples": Counter(),
            "min_len": [], "max_len": []}
        for i in range(N_FIELDS)
    }
    widths = []
    for p in picks:
        width, profiles = discover_layout(p, n_rows=n_rows, stride=11)
        widths.append(width)
        for pr in profiles:
            if pr.idx not in agg:
                continue
            a = agg[pr.idx]
            a["fill"].append(pr.fill_rate)
            a["distinct"].append(pr.n_distinct)
            a["min_len"].append(pr.min_len)
            a["max_len"].append(pr.max_len)
            for ex in pr.examples:
                a["examples"][ex] += 1

    out = {}
    for i, a in agg.items():
        if not a["fill"]:
            continue
        out[i] = {
            "fill_rate": sum(a["fill"]) / len(a["fill"]),
            "max_distinct": max(a["distinct"]) if a["distinct"] else 0,
            "examples": [e for e, _ in a["examples"].most_common(3)],
            "min_len": min(a["min_len"]) if a["min_len"] else 0,
            "max_len": max(a["max_len"]) if a["max_len"] else 0,
        }
    return {"files_profiled": [p.name for p in picks], "widths": widths,
            "columns": out}


def _fmt_examples(ex: list[str], limit: int = 3) -> str:
    if not ex:
        return "_(empty)_"
    vals = [e if len(e) <= 22 else e[:19] + "..." for e in ex[:limit]]
    return ", ".join(f"`{v}`" for v in vals)


def build(profile: dict | None = None) -> Path:
    profile = profile or profile_corpus()
    cols = profile.get("columns", {})
    corpus = corpus_summary()

    used = set(USED_IDX)
    by_kind = Counter(f.kind for f in FIELDS)
    n_verified = sum(1 for f in FIELDS if f.verified)

    L: list[str] = []
    A = L.append

    A("# Data Dictionary — Fannie Mae Single-Family Loan Performance")
    A("")
    A("**Generated by** `ml/profiling/data_dictionary.py` "
      f"| schema contract `{CFG.schema_version}` | config `{CFG.config_version}`")
    A("")
    A("This dictionary enumerates **every one of the 113 positional fields** in "
      "the delivered raw files, as required by `dataset_usage.md` §17.3 Rule 3. "
      "Fill rates, cardinalities and example values are **empirically observed**, "
      "not copied from the published layout — the mapping is evidence-backed.")
    A("")

    # ---------------- corpus ----------------
    A("## 1. Corpus")
    A("")
    A("| Measure | Value |")
    A("|---|---|")
    A(f"| Archives | {corpus['n_archives']} quarterly ZIPs |")
    A(f"| Compressed on disk | {corpus['compressed_gb']:.2f} GB |")
    A(f"| Uncompressed | **{corpus['uncompressed_gb']:.2f} GB** |")
    A(f"| Mean compression ratio | {corpus['mean_compression_ratio']:.2f}x |")
    A(f"| Largest single member | {corpus['largest_member_gb']:.2f} GB |")
    A(f"| Format | pipe-delimited, **no header row**, {N_FIELDS} positional fields |")
    A(f"| Files profiled for this dictionary | {', '.join(profile.get('files_profiled', []))} |")
    A("")
    A("Every archive was verified to contain exactly "
      f"{N_FIELDS} fields before ingestion trusted any positional mapping "
      "(`schema_detection.verify_contract`); a width mismatch raises rather than "
      "silently corrupting the mapping.")
    A("")
    A("> **Files are never extracted.** 205 GB uncompressed against 56 GB of free "
      "disk makes extraction impossible, so every member is streamed directly "
      "from its ZIP. See `data/extracted/README.md`.")
    A("")

    # ---------------- field classification ----------------
    A("## 2. Field Classification")
    A("")
    A("Columns are classified into the four functional groups "
      "`dataset_usage.md` §17.3 Rule 3 asks for, plus two the raw layout forces:")
    A("")
    A("| Class | Count | Meaning |")
    A("|---|---|---|")
    A(f"| Identifier | {by_kind[IDENTIFIER]} | Keys linking the tables |")
    A(f"| Time | {by_kind[TIME]} | Monthly observation and date fields |")
    A(f"| Acquisition | {by_kind[ACQUISITION]} | Origination-level, constant per loan |")
    A(f"| Performance | {by_kind[PERFORMANCE]} | Monthly-varying servicing observations |")
    A(f"| Credit event | {by_kind[CREDIT_EVENT]} | Termination and loss fields |")
    A(f"| Unused | {by_kind[UNUSED]} | Present in the layout but empty or out of scope |")
    A("")
    A(f"**{len(used)} of {N_FIELDS} fields are parsed.** Column pruning is the "
      "single largest throughput win available: parsing 45 of 113 fields roughly "
      "triples read speed over ~870M rows.")
    A("")
    A(f"**{n_verified} of {N_FIELDS} fields are marked verified** — their "
      "positional mapping was confirmed against observed value ranges, formats "
      "and cross-field consistency. The remainder are consistently empty in this "
      "vintage; they are named for completeness and **nothing in the pipeline "
      "depends on them**. Three trailing positions (110–112) could not be "
      "confirmed against the published layout and are labelled `UNVERIFIED_*` "
      "rather than being given a speculative name.")
    A("")

    # ---------------- the full table ----------------
    A("## 3. Complete Field Reference (all 113 positions)")
    A("")
    A("`Fill%` and `Distinct` are observed on a strided sample across four "
      "archives. `P` marks a field the pipeline parses.")
    A("")
    A("| # | P | Field | Class | Type | Fill% | Distinct | Examples | Meaning | ML usage |")
    A("|---:|:-:|---|---|---|---:|---:|---|---|---|")
    for f in FIELDS:
        c = cols.get(f.idx, {})
        fill = c.get("fill_rate")
        fill_s = f"{fill * 100:.1f}" if fill is not None else "—"
        dist = c.get("max_distinct")
        dist_s = f"{dist:,}" if dist else "0"
        ex = _fmt_examples(c.get("examples", []))
        mark = "✓" if f.idx in used else ""
        name = f"`{f.name}`" + ("" if f.verified else " ⚠")
        A(f"| {f.idx} | {mark} | {name} | {KIND_LABEL[f.kind]} | {f.dtype} | "
          f"{fill_s} | {dist_s} | {ex} | {f.meaning} | {f.ml_usage} |")
    A("")
    A("⚠ = positional mapping not empirically verified (field is empty or "
      "ambiguous in this vintage); unused by the pipeline.")
    A("")

    # ---------------- the bridge ----------------
    A("## 4. Schema Bridge — Raw → Canonical")
    A("")
    A("The project documentation (`api_spec.md`, `database_schema.md`, "
      "`dataset_usage.md` §4) describes a **curated** schema with fields like "
      "`loan_id`, `credit_score_band`, `current_status`, `default_flag`. The "
      "delivered data is the **raw** Fannie Mae layout. This table is the bridge "
      "between them — the Gap 1 decision in `docs/documentation_analysis.md` §3.")
    A("")
    A("### 4.1 Direct renames")
    A("")
    A("| Raw field | Canonical field | Transformation |")
    A("|---|---|---|")
    for raw, canon, tr in [
        ("LOAN_ID", "loan_id", "strip whitespace"),
        ("ACT_PERIOD", "reporting_month", "`MMYYYY` → month-start timestamp"),
        ("ORIG_DATE", "origination_month", "`MMYYYY` → month-start timestamp"),
        ("ORIG_UPB", "original_balance", "→ float32"),
        ("CURRENT_UPB", "current_balance", "→ float32, zero-balance repair (§4.4)"),
        ("ORIG_RATE", "interest_rate", "→ float32"),
        ("CURR_RATE", "current_interest_rate", "→ float32"),
        ("LOAN_AGE", "loan_age_months", "→ Int16"),
        ("REM_MONTHS", "remaining_term_months", "→ Int16"),
        ("CSCORE_B", "credit_score", "→ float32, retained alongside its band"),
        ("OLTV", "ltv", "→ float32, retained alongside its band"),
        ("DTI", "dti", "→ float32, retained alongside its band"),
        ("STATE", "state", "explicit `Unknown` for blanks"),
        ("SERVICER", "servicer_name", "explicit `Unknown` for blanks"),
        ("MOD_FLAG", "modification_flag", "`Y` → true"),
        ("FORBEARANCE_INDICATOR", "forbearance_flag", "not in {blank, `N`, `7`} → true"),
    ]:
        A(f"| `{raw}` | `{canon}` | {tr} |")
    A("")

    A("### 4.2 Coded-value decoding")
    A("")
    A("| Raw field | Code | Canonical value |")
    A("|---|---|---|")
    for raw, mapping in (
        ("PURPOSE", {"P": "purchase", "C": "cash_out_refinance", "R": "refinance"}),
        ("PROP", {"SF": "single_family", "PU": "planned_urban_development",
                  "CO": "condominium", "CP": "cooperative", "MH": "manufactured_home"}),
        ("OCC_STAT", {"P": "principal", "I": "investor", "S": "second_home"}),
        ("CHANNEL", {"R": "retail", "C": "correspondent", "B": "broker"}),
        ("MI_TYPE", {"1": "borrower_paid", "2": "lender_paid", "3": "investor_paid"}),
    ):
        for code, val in mapping.items():
            A(f"| `{raw}` | `{code}` | `{val}` |")
    A("")

    A("### 4.3 Banding — continuous → documented categorical")
    A("")
    A("`api_spec.md` contracts on banded strings such as `\"680-719\"`, "
      "`\"80-90\"`, `\"36-43\"`. Cut-points are chosen to reproduce those "
      "examples. **The continuous source value is always retained alongside the "
      "band**, so the API contract holds while models keep full numeric "
      "resolution — banding is additive, never lossy.")
    A("")
    b = CFG.bands
    for label, src, edges, labels in (
        ("credit_score_band", "CSCORE_B", b.credit_score_edges, b.credit_score_labels),
        ("ltv_band", "OLTV", b.ltv_edges, b.ltv_labels),
        ("dti_band", "DTI", b.dti_edges, b.dti_labels),
    ):
        A(f"**`{label}`** from `{src}` — left-closed intervals:")
        A("")
        A("| Band | Range |")
        A("|---|---|")
        for i, lab in enumerate(labels):
            A(f"| `{lab}` | [{edges[i]}, {edges[i+1]}) |")
        A(f"| `{b.unknown_label}` | value missing or unparseable |")
        A("")

    A("### 4.4 Derived fields — the target-critical logic")
    A("")
    A("Every label in the project descends from **two raw fields**. This is the "
      "highest-risk mapping in the build and is unit-tested in "
      "`tests/test_targets.py` (25 cases).")
    A("")
    A("**`DLQ_STATUS` → delinquency**")
    A("")
    A("| Raw | Meaning | `dlq_months` | `days_past_due` |")
    A("|---|---|---|---|")
    for code, months in (("00", "current"), ("01", "30 days"), ("02", "60 days"),
                         ("03", "90 days"), ("06", "180 days"), ("12", "360 days")):
        n = int(code)
        A(f"| `{code}` | {months} | {n} | {n * 30} |")
    A("| `XX` / blank | **servicer did not report** | `NaN` | `NaN` |")
    A("")
    A("`XX` is deliberately **not** mapped to zero. An unreported status is not "
      "a current loan, and conflating the two would understate risk. The "
      "missingness is preserved, flagged as `dlq_status_unreported`, and "
      "surfaced as data-quality rule **R008**.")
    A("")
    A("**`Zero_Bal_Code` → terminal state.** Populated only on a loan's final "
      "record, when the balance reaches zero:")
    A("")
    A("| Code | Meaning | Canonical state | Flags set |")
    A("|---|---|---|---|")
    for code, meaning in ZERO_BAL_MAP.items():
        if code in CFG.rules.zb_prepaid:
            st, fl = "`Prepaid`", "`prepayment_flag`"
        elif code in CFG.rules.zb_credit_event:
            st, fl = "`Default`", "`default_flag`, `default_flag_credit_event`"
        else:
            st, fl = "`Closed`", "—"
        A(f"| `{code}` | {meaning} | {st} | {fl} |")
    A("")
    A("**Loan state machine.** Terminal codes take precedence over delinquency "
      "depth, so a loan that pays off while delinquent is `Prepaid`, not "
      "`Delinquent`:")
    A("")
    A("```")
    A("if   Zero_Bal_Code == '01'                -> Prepaid   (terminal)")
    A("elif Zero_Bal_Code in {02,03,09,15}       -> Default   (terminal, credit event)")
    A("elif Zero_Bal_Code in {06,16}             -> Closed    (terminal)")
    A(f"elif dlq_months >= {CFG.rules.default_dlq_months}"
      f"                     -> Default   (D{CFG.rules.default_dlq_months * 30})")
    A(f"elif dlq_months >= {CFG.rules.delinquency_dlq_months}"
      f"                     -> Delinquent")
    A("else                                      -> Current")
    A("```")
    A("")
    A("**Three default definitions are materialised, not one.** COVID-era "
      "forbearance pushed many loans past 180 days delinquent without an "
      "economic default, because missed payments under an approved plan still "
      "accrue as delinquency. Rather than quietly pick one definition:")
    A("")
    A("| Field | Definition | Role |")
    A("|---|---|---|")
    A("| `default_flag` | D180 **or** credit event | Primary; the documented definition (assumption A4) |")
    A("| `default_flag_credit_event` | terminal credit event only | Unambiguous economic default |")
    A("| `default_flag_ex_forbearance` | credit event **or** (D180 **and** not in forbearance) | Forbearance-adjusted |")
    A("")
    A("`forbearance_flag` is also supplied as a model feature so the classifier "
      "can separate relief-driven delinquency from genuine deterioration.")
    A("")
    A("**Zero-balance repair.** Fannie Mae systematically reports "
      "`CURRENT_UPB = 0.00` on a loan's earliest records, before the servicer's "
      "first full balance submission — verified: in the 2019Q1 file *every* "
      "record in the first reporting month (129,126 rows) carries a zero "
      "balance. A zero balance on a non-terminal row is a reporting artifact, "
      "not a paid-off loan; feeding it to a model as a real zero would corrupt "
      "every balance ratio and make new loans look fully amortised. Repair is "
      "forward-fill (mid-history gaps) then back-fill (leading zeros), both "
      "flagged via `balance_imputed`; loans whose entire history is zero remain "
      "`NaN` rather than being filled with a fabricated number.")
    A("")

    # ---------------- canonical tables ----------------
    A("## 5. Canonical Output Tables")
    A("")
    A("### 5.1 `loan_static_attributes.parquet` — one row per loan")
    A("")
    A("| Column | Purpose |")
    A("|---|---|")
    for c in CANONICAL_STATIC:
        A(f"| `{c}` | {_static_purpose(c)} |")
    A("")
    A("### 5.2 `loan_monthly_performance.parquet` — one row per loan-month")
    A("")
    A("| Column | Purpose |")
    A("|---|---|")
    for c in CANONICAL_MONTHLY:
        A(f"| `{c}` | {_monthly_purpose(c)} |")
    A("")
    A("### 5.3 Join logic")
    A("")
    A("```")
    A("loan_static_attributes  ──┐")
    A("                          ├── join on loan_id ──> loan-month panel")
    A("loan_monthly_performance ─┘        (1 row = 1 loan at 1 month)")
    A("```")
    A("")
    A("`month_index` is **derived**, not present in the raw data: a per-loan "
      "sequential counter over sorted `reporting_month`, starting at 0 "
      "(assumption A8). It is computed during the streaming pass, which is exact "
      "because loan sets are disjoint across quarterly files and a loan's rows "
      "are contiguous and month-ordered within a file — both verified empirically.")
    A("")

    # ---------------- assumptions ----------------
    A("## 6. Assumptions")
    A("")
    A("| # | Assumption | Basis | Risk if wrong |")
    A("|---|---|---|---|")
    for n, a, basis, risk in (
        ("A1", "The 113 positional fields follow the published Fannie Mae layout",
         "Every position profiled; value ranges, formats and cross-field consistency agree",
         "Mis-mapped features — mitigated by profiling plus derived-field unit tests"),
        ("A2", "`DLQ_STATUS` is months-delinquent as a 2-char code",
         "Observed value set {00..18, XX} with the expected monotone frequency decay",
         "Wrong delinquency labels; highest-impact risk, unit-tested"),
        ("A3", "`Zero_Bal_Code` 01=prepaid, {02,03,09,15}=credit event, {06,16}=closed",
         "Fannie Mae published code list; `01` dominant as expected",
         "Prepayment and default inverted — two economically opposite outcomes"),
        ("A4", f"Default = {CFG.rules.default_dlq_months * 30}+ days delinquent or a credit event",
         "Industry-standard D180; `prd.md` says \"a defined default state\" without fixing it",
         "Shifts the base rate; all three definitions are reported"),
        ("A5", "Band cut-points for credit score / LTV / DTI",
         "Chosen to reproduce the literal examples in `api_spec.md`",
         "Cosmetic only — continuous values are retained"),
        ("A8", "`month_index` is a derived per-loan sequential counter",
         "`dataset_usage.md` §4.1 defines it as such; absent from raw data",
         "None — derived deterministically from sorted `reporting_month`"),
    ):
        A(f"| {n} | {a} | {basis} | {risk} |")
    A("")
    A("---")
    A("")
    A("*Regenerate with* `python -m ml.profiling.data_dictionary`")

    OUT_PATH.write_text("\n".join(L), encoding="utf-8")
    (REFERENCE_DIR / "schema_profile.json").write_text(
        json.dumps(profile, indent=2, default=str))
    return OUT_PATH


